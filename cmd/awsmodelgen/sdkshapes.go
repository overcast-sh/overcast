// The runtime SDK shape tables.
//
// Step Functions' `arn:aws:states:::aws-sdk:<service>:<action>` integrations
// have to turn a JSON parameter object into a real wire request for whichever
// protocol the target service speaks, and its wire response back into JSON —
// which needs the operation's input and output shapes. The routing manifest
// carries none, and the committed snapshot (shapes.go) is generator input only
// and scoped to a handful of services.
//
// So the same pruner cuts a third artifact: for a reviewed list of services
// (models/aws/sdk-shapes-services.txt — the services Overcast implements), one
// compiled-in Go file per service under internal/awsshapes holding exactly the
// facts a wire translator needs — shape kinds, member names and targets, and the
// serialisation and HTTP-binding traits — as a line-per-shape string constant.
// The package decodes one service's table lazily, the first time a workflow
// calls that service, so the daemon reads no model data at startup and none at
// all unless a state machine uses an SDK integration.
//
// Enum values, documentation, validation constraints, pagination and resource
// lifecycles are all dropped: the translator never consults them, and every
// byte here is compiled into every binary.

// sdkShapeTraitAllowlist is what the runtime tables keep. Each entry is a trait
// the translator in internal/awsshapes reads.
var sdkShapeTraitAllowlist = map[string]struct{}{
	"smithy.api#timestampFormat":       {},
	"smithy.api#error":                 {},
	"smithy.api#httpError":             {},
	"smithy.api#http":                  {},
	"smithy.api#httpLabel":             {},
	"smithy.api#httpQuery":             {},
	"smithy.api#httpQueryParams":       {},
	"smithy.api#httpHeader":            {},
	"smithy.api#httpPrefixHeaders":     {},
	"smithy.api#httpPayload":           {},
	"smithy.api#httpResponseCode":      {},
	"smithy.api#jsonName":              {},
	"smithy.api#xmlName":               {},
	"smithy.api#xmlFlattened":          {},
	"smithy.api#xmlAttribute":          {},
	"smithy.api#xmlNamespace":          {},
	"smithy.api#streaming":             {},
	"aws.protocols#awsQueryError":      {},
	"aws.protocols#ec2QueryName":       {},
	"aws.protocols#awsQueryCompatible": {},
}

// SDKShapesDigestField names the provenance entry recording the SHA-256 of the
// generated runtime SDK shape tables.
const SDKShapesDigestField = "sdk-shapes-sha256"

// sdkShapesFileSuffix marks a generated table inside internal/awsshapes, so the
// writer and the checker can tell generated files from the hand-written
// decoder that lives beside them.
const sdkShapesFileSuffix = ".gen.go"

// buildSDKShapes renders one Go file per listed service plus an index, keyed by
// file name.
func buildSDKShapes(modelsDir string, services []string) (map[string][]byte, error) {
	snapshots, err := pruneServices(modelsDir, services, sdkShapeTraitAllowlist)
	if err != nil {
		return nil, err
	}
	files := make(map[string][]byte, len(snapshots)+1)
	names := make([]string, 0, len(snapshots))
	for service := range snapshots {
		names = append(names, service)
	}
	sort.Strings(names)
	var index bytes.Buffer
	index.WriteString("// Code generated by cmd/awsmodelgen; DO NOT EDIT.\n\npackage awsshapes\n\n")
	index.WriteString("// tables lists every service's encoded shape table, sorted by service key.\n")
	index.WriteString("var tables = [...]table{\n")
	for _, service := range names {
		text, err := renderSDKShapes(snapshots[service])
		if err != nil {
			return nil, fmt.Errorf("sdk shapes for %s: %w", service, err)
		}
		ident := sdkShapesIdent(service)
		var file bytes.Buffer
		file.WriteString("// Code generated by cmd/awsmodelgen; DO NOT EDIT.\n\npackage awsshapes\n\n")
		fmt.Fprintf(&file, "const %s = `%s`\n", ident, text)
		formatted, err := format.Source(file.Bytes())
		if err != nil {
			return nil, fmt.Errorf("format sdk shapes for %s: %w", service, err)
		}
		files["shapes_"+strings.ReplaceAll(service, "-", "_")+sdkShapesFileSuffix] = formatted
		fmt.Fprintf(&index, "\t{service: %q, encoded: %s},\n", service, ident)
	}
	index.WriteString("}\n")
	formatted, err := format.Source(index.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format sdk shapes index: %w", err)
	}
	files["index"+sdkShapesFileSuffix] = formatted
	return files, nil
}

// sdkShapesIdent is the Go constant holding a service's table.
func sdkShapesIdent(service string) string {
	var out strings.Builder
	out.WriteString("shapes")
	upper := true
	for _, r := range service {
		if r == '-' {
			upper = true
			continue
		}
		if upper {
			out.WriteString(strings.ToUpper(string(r)))
			upper = false
			continue
		}
		out.WriteRune(r)
	}
	return out.String()
}

// renderSDKShapes emits one service's table. The format is the contract with
// the decoder in internal/awsshapes/awsshapes.go:
//
//	service <protocol,…> [version=…] [ns=<uri>] [querycompat]
//	<Shape> <kind> [attr …]
//	.<Member> <target> [attr …]
//
// one shape per line in sorted order, each followed by its members in sorted
// order. Attributes are `key=value` or bare flags, space separated. A target
// with no '#' names a shape in this table; `~Name` is a Smithy prelude shape;
// anything else is a fully qualified shape in another namespace.
func renderSDKShapes(snapshot awsmodel.Snapshot) (string, error) {
	var out strings.Builder
	header := []string{"service", strings.Join(snapshot.Protocols, ",")}
	if snapshot.APIVersion != "" {
		header = append(header, "version="+snapshot.APIVersion)
	}
	if svc, ok := snapshot.Shapes[snapshot.ServiceShape]; ok {
		if ns, ok := svc.Traits["smithy.api#xmlNamespace"]; ok {
			var trait struct {
				URI string `json:"uri"`
			}
			if err := json.Unmarshal(ns, &trait); err != nil {
				return "", fmt.Errorf("service xmlNamespace: %w", err)
			}
			header = append(header, "ns="+trait.URI)
		}
		if _, ok := svc.Traits["aws.protocols#awsQueryCompatible"]; ok {
			header = append(header, "querycompat")
		}
	}
	if err := writeSDKLine(&out, header); err != nil {
		return "", err
	}
	names := make([]string, 0, len(snapshot.Shapes))
	for name, shape := range snapshot.Shapes {
		switch shape.Type {
		case "service", "resource":
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		shape := snapshot.Shapes[name]
		fields := []string{name, shape.Type}
		attrs, err := sdkShapeAttrs(shape)
		if err != nil {
			return "", fmt.Errorf("shape %s: %w", name, err)
		}
		if err := writeSDKLine(&out, append(fields, attrs...)); err != nil {
			return "", fmt.Errorf("shape %s: %w", name, err)
		}
		// Enum members are wire values, which the translator passes through
		// as strings; they are the largest thing it would never read.
		if shape.Type == "enum" || shape.Type == "intEnum" {
			continue
		}
		members := make([]string, 0, len(shape.Members))
		for member := range shape.Members {
			members = append(members, member)
		}
		sort.Strings(members)
		for _, member := range members {
			m := shape.Members[member]
			attrs, err := sdkTraitAttrs(m.Traits)
			if err != nil {
				return "", fmt.Errorf("member %s.%s: %w", name, member, err)
			}
			line := append([]string{"." + member, sdkTarget(m.Target)}, attrs...)
			if err := writeSDKLine(&out, line); err != nil {
				return "", fmt.Errorf("member %s.%s: %w", name, member, err)
			}
		}
	}
	return out.String(), nil
}

// sdkTarget spells a reference: prelude shapes shrink to `~Name`.
func sdkTarget(target string) string {
	if rest, ok := strings.CutPrefix(target, "smithy.api#"); ok {
		return "~" + rest
	}
	return target
}

// sdkShapeAttrs renders the shape-level fields and traits.
func sdkShapeAttrs(shape awsmodel.SnapshotShape) ([]string, error) {
	var attrs []string
	add := func(key, value string) {
		if value != "" {
			attrs = append(attrs, key+"="+value)
		}
	}
	add("in", sdkTargetOrEmpty(shape.Input))
	add("out", sdkTargetOrEmpty(shape.Output))
	if len(shape.Errors) > 0 {
		errs := make([]string, len(shape.Errors))
		for i, e := range shape.Errors {
			errs[i] = sdkTarget(e)
		}
		add("err", strings.Join(errs, ","))
	}
	add("m", sdkTargetOrEmpty(shape.Member))
	add("k", sdkTargetOrEmpty(shape.Key))
	add("v", sdkTargetOrEmpty(shape.Value))
	for _, nested := range []struct {
		key    string
		traits map[string]json.RawMessage
	}{{"mxml", shape.MemberTraits}, {"kxml", shape.KeyTraits}, {"vxml", shape.ValueTraits}} {
		if raw, ok := nested.traits["smithy.api#xmlName"]; ok {
			var name string
			if err := json.Unmarshal(raw, &name); err != nil {
				return nil, fmt.Errorf("%s: %w", nested.key, err)
			}
			add(nested.key, name)
		}
	}
	traits, err := sdkTraitAttrs(shape.Traits)
	if err != nil {
		return nil, err
	}
	return append(attrs, traits...), nil
}

func sdkTargetOrEmpty(target string) string {
	if target == "" {
		return ""
	}
	return sdkTarget(target)
}

// sdkTraitAttrs renders allowlisted traits in a fixed order.
func sdkTraitAttrs(traits map[string]json.RawMessage) ([]string, error) {
	if len(traits) == 0 {
		return nil, nil
	}
	names := make([]string, 0, len(traits))
	for name := range traits {
		names = append(names, name)
	}
	sort.Strings(names)
	var attrs []string
	for _, name := range names {
		raw := traits[name]
		str := func() (string, error) {
			var s string
			err := json.Unmarshal(raw, &s)
			return s, err
		}
		var err error
		var value string
		switch name {
		case "smithy.api#timestampFormat":
			value, err = str()
			attrs = append(attrs, "ts="+value)
		case "smithy.api#error":
			value, err = str()
			attrs = append(attrs, "error="+value)
		case "smithy.api#httpError":
			var code int
			err = json.Unmarshal(raw, &code)
			attrs = append(attrs, "code="+strconv.Itoa(code))
		case "smithy.api#http":
			var trait struct {
				Method string `json:"method"`
				URI    string `json:"uri"`
				Code   int    `json:"code"`
			}
			err = json.Unmarshal(raw, &trait)
			attrs = append(attrs, "method="+trait.Method, "uri="+trait.URI)
			if trait.Code != 0 {
				attrs = append(attrs, "code="+strconv.Itoa(trait.Code))
			}
		case "smithy.api#httpLabel":
			attrs = append(attrs, "label")
		case "smithy.api#httpQuery":
			value, err = str()
			attrs = append(attrs, "query="+value)
		case "smithy.api#httpQueryParams":
			attrs = append(attrs, "qparams")
		case "smithy.api#httpHeader":
			value, err = str()
			attrs = append(attrs, "header="+value)
		case "smithy.api#httpPrefixHeaders":
			value, err = str()
			attrs = append(attrs, "prefix="+value)
		case "smithy.api#httpPayload":
			attrs = append(attrs, "payload")
		case "smithy.api#httpResponseCode":
			attrs = append(attrs, "status")
		case "smithy.api#jsonName":
			value, err = str()
			attrs = append(attrs, "json="+value)
		case "smithy.api#xmlName":
			value, err = str()
			attrs = append(attrs, "xml="+value)
		case "smithy.api#xmlFlattened":
			attrs = append(attrs, "flat")
		case "smithy.api#xmlAttribute":
			attrs = append(attrs, "attr")
		case "smithy.api#xmlNamespace":
			var trait struct {
				URI    string `json:"uri"`
				Prefix string `json:"prefix"`
			}
			err = json.Unmarshal(raw, &trait)
			attrs = append(attrs, "ns="+trait.URI)
			if trait.Prefix != "" {
				attrs = append(attrs, "nsprefix="+trait.Prefix)
			}
		case "smithy.api#streaming":
			attrs = append(attrs, "stream")
		case "aws.protocols#awsQueryError":
			var trait struct {
				Code string `json:"code"`
			}
			err = json.Unmarshal(raw, &trait)
			attrs = append(attrs, "qerr="+trait.Code)
		case "aws.protocols#ec2QueryName":
			value, err = str()
			attrs = append(attrs, "ec2="+value)
		case "aws.protocols#awsQueryCompatible":
			// A service-level fact, rendered in the header line.
		default:
			return nil, fmt.Errorf("trait %s is allowlisted but has no rendering", name)
		}
		if err != nil {
			return nil, fmt.Errorf("trait %s: %w", name, err)
		}
	}
	return attrs, nil
}

// writeSDKLine joins one line's fields, refusing any value that would break the
// format or the raw string literal it is emitted into.
func writeSDKLine(out *strings.Builder, fields []string) error {
	for _, field := range fields {
		if strings.ContainsAny(field, " \t\n\r`") {
			return fmt.Errorf("value %q cannot be encoded in an SDK shape table", field)
		}
	}
	out.WriteString(strings.Join(fields, " "))
	out.WriteByte('\n')
	return nil
}

// writeOrCheckSDKShapes writes the tables, or in check mode proves the
// committed ones are byte-for-byte what the generator just produced. Only
// generated files are considered: the package's hand-written decoder lives in
// the same directory.
func writeOrCheckSDKShapes(dir string, files map[string][]byte, check bool) error {
	existing, err := listSDKShapeFiles(dir)
	if err != nil {
		return err
	}
	if check {
		for name := range existing {
			if _, wanted := files[name]; !wanted {
				return fmt.Errorf("%s holds %s, which no listed service produces; regenerate with make generate-aws-operations", dir, name)
			}
		}
		names := make([]string, 0, len(files))
		for name := range files {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			current, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return fmt.Errorf("read sdk shapes %s: %w", name, err)
			}
			if !bytes.Equal(current, files[name]) {
				return fmt.Errorf("%s is stale; run make generate-aws-operations with the pinned AWS model checkout", filepath.Join(dir, name))
			}
		}
		return nil
	}
	for name := range existing {
		if _, wanted := files[name]; !wanted {
			if err := os.Remove(filepath.Join(dir, name)); err != nil {
				return fmt.Errorf("remove stale sdk shapes %s: %w", name, err)
			}
		}
	}
	for name, contents := range files {
		if err := os.WriteFile(filepath.Join(dir, name), contents, 0o644); err != nil {
			return fmt.Errorf("write sdk shapes %s: %w", name, err)
		}
	}
	return nil
}

func listSDKShapeFiles(dir string) (map[string]struct{}, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("read sdk shapes directory %s: %w", dir, err)
	}
	files := make(map[string]struct{}, len(entries))
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), sdkShapesFileSuffix) {
			files[entry.Name()] = struct{}{}
		}
	}
	return files, nil
}
