// The Rust emitter, over the same hermetic fixture the rest of the generator's
// tests use (testdata/shapes/widgets.json + testdata/recipes/widgets.json).
// Nothing here reads the committed corpus, opens a network connection or
// compiles the emitted source; the emitted corpus is proved to compile by the
// rust-sdk suite's own Docker build, which runs `cargo test` before `cargo
// build`.

// rustGoldenPath is the emitted source for the fixture service. It carries a
// .golden suffix so no Rust tool treats it as part of any crate: it names an
// aws-sdk crate for a service that does not exist.
const rustGoldenPath = "testdata/golden/scenarios_widgets_gen.rs.golden"

func TestEmitRust_matchesTheGoldenSource(t *testing.T) {
	// Given: the fixture service, generated.
	_, gen := generateFixture(t)

	// When: it is emitted as Rust.
	emission, err := emitRust(gen)
	if err != nil {
		t.Fatalf("emitRust: %v", err)
	}

	// Then: byte for byte what is committed.
	if emission.Path != "compat/suites/rust-sdk/src/groups/scenarios_widgets_gen.rs" {
		t.Errorf("emitted path = %s", emission.Path)
	}
	assertGolden(t, rustGoldenPath, emission.Contents)
}

func TestEmitRust_isDeterministic(t *testing.T) {
	_, gen := generateFixture(t)

	first, err := emitRust(gen)
	if err != nil {
		t.Fatalf("emitRust: %v", err)
	}
	second, err := emitRust(gen)
	if err != nil {
		t.Fatalf("emitRust: %v", err)
	}
	if string(first.Contents) != string(second.Contents) {
		t.Error("two emissions of one scenario differ; the byte-identical regeneration gate would fail at random")
	}
}

// TestEmitRust_emitsEveryGroupAndTest keeps the emitted registrations in step
// with the scenario. A test the emitter silently dropped would report as a hard
// failure in the suite (the generated-no-backend rule), which is loud but late —
// and the suite's own registration test would catch it a build earlier.
func TestEmitRust_emitsEveryGroupAndTest(t *testing.T) {
	_, gen := generateFixture(t)
	emission, err := emitRust(gen)
	if err != nil {
		t.Fatalf("emitRust: %v", err)
	}
	source := string(emission.Contents)
	for _, g := range gen.scenario.Groups {
		for _, tc := range g.Tests {
			key := `"` + g.Name + ":" + tc.Name + `"`
			if !strings.Contains(source, key) {
				t.Errorf("no impl registered under %s", key)
			}
			if !strings.Contains(source, "fn "+rustNameTestFn(g.Name, tc.Name)+"(") {
				t.Errorf("no function emitted for %s/%s", g.Name, tc.Name)
			}
		}
		// Every group registers both hooks, even the probe group whose two
		// lists are empty: an empty phase is a no-op, not a missing one.
		for _, fn := range []string{rustNameSetupFn(g.Name), rustNameTeardownFn(g.Name)} {
			if !strings.Contains(source, "fn "+fn+"(") {
				t.Errorf("no %s emitted for %s", fn, g.Name)
			}
		}
	}
	if !strings.Contains(source, "// Code generated by cmd/compatgen; DO NOT EDIT.") {
		t.Error("the generated-file marker is missing")
	}
}

// TestEmitRust_refusesWhatItCannotSpell pins every refusal this backend
// introduces, and what each costs: the group leaves the rust-sdk column rather
// than being emitted as a guess or dropped silently.
//
// There are two, and neither arises from a committed scenario. The list is
// shorter than the Go emitter's because Rust's fluent setters take the value
// itself rather than an Option: a member's optionality never reaches the call
// site, so there is no pointer-vs-value question to get wrong and no
// value-typed zero the SDK would drop.
func TestEmitRust_refusesWhatItCannotSpell(t *testing.T) {
	for _, tc := range []struct {
		name       string
		op         string
		params     map[string]any
		wantMember string
		wantDetail string
	}{
		{
			// The fixture models ListWidgets with an optional CreatedAfter
			// targeting smithy.api#Timestamp. No value in the IR's grammar can
			// carry one, and saying that in the model's own vocabulary is more
			// use to a recipe author than naming a Rust type.
			name:       "a member whose modeled kind has no IR literal",
			op:         "ListWidgets",
			params:     map[string]any{"CreatedAfter": "2026-09-06T00:00:00Z"},
			wantMember: "CreatedAfter",
			wantDetail: "timestamp",
		},
		{
			// A deferred expression resolves into one scalar slot. A whole list
			// from a $ref has none: the SDK's setter takes one typed element at
			// a time, and building the composite at run time would mean turning
			// a document into typed values with no type to turn it into.
			name:       "an expression bound to a composite member",
			op:         "UntagWidget",
			params:     map[string]any{"TagKeys": map[string]any{"$ref": "tags.keys"}},
			wantMember: "TagKeys",
			wantDetail: "can only be bound to a scalar member",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			// Given: a group whose call carries that member.
			_, gen := generateFixture(t)
			const name = "widgets-gen-refused"
			gen.scenario.Groups = append(gen.scenario.Groups, group{
				Name: name,
				Kind: groupLifecycle,
				Tests: []test{newTest(tc.op, tc.op, call{Op: tc.op, Params: tc.params},
					responseField(checks("$.Widgets", isList())))},
			})

			// When: the service is emitted.
			emission, err := emitRust(gen)
			if err != nil {
				t.Fatalf("emitRust: %v", err)
			}

			// Then: the group is not in the emitted source, it is reported as
			// unable so the registry scopes it away from rust-sdk, and the
			// refusal names the member and says why.
			if strings.Contains(string(emission.Contents), name) {
				t.Error("a group the emitter cannot spell was emitted anyway")
			}
			if !emission.Refused[name] {
				t.Fatal("the refused group was not reported as unable")
			}
			if len(emission.Gaps) != 1 {
				t.Fatalf("gaps = %+v, want one", emission.Gaps)
			}
			got := emission.Gaps[0]
			if got.Reason != rustEmitReason+":"+tc.wantMember || got.Operation != tc.op || got.Group != name {
				t.Errorf("gap = %+v", got)
			}
			if !strings.Contains(got.Detail, tc.wantDetail) {
				t.Errorf("gap detail does not say why: %q, want it to mention %q", got.Detail, tc.wantDetail)
			}
		})
	}
}

// TestRustCallLines_spellsEveryShapeOfMember is the naming table read back, one
// row at a time. The golden file proves what a whole service comes out as; this
// says which rule produced each piece of it, and it is where a new rule is added
// with its own row.
func TestRustCallLines_spellsEveryShapeOfMember(t *testing.T) {
	_, gen := generateFixture(t)
	const crate = "aws_sdk_widgets"
	for _, tc := range []struct {
		name   string
		op     string
		params string
		want   []string
	}{
		{
			"a string and an enum, as literals", "CreateWidget",
			`{"Color":"blue","Description":"one"}`,
			[]string{
				`    .color(aws_sdk_widgets::types::Color::from("blue"))`,
				`    .description("one")`,
			},
		},
		{
			"a value-typed number, which Rust sends whatever it is", "RotateWidget",
			`{"Angle":0}`,
			[]string{"    .angle(0)"},
		},
		{
			"a string map, one setter call per entry", "TagWidget",
			`{"Tags":{"compat":"scenario","team":"platform"}}`,
			[]string{
				`    .tags("compat", "scenario")`,
				`    .tags("team", "platform")`,
			},
		},
		{
			"a list of strings, one setter call per element", "UntagWidget",
			`{"TagKeys":["compat","team"]}`,
			[]string{`    .tag_keys("compat")`, `    .tag_keys("team")`},
		},
		{
			// A structure with no required member has an infallible builder.
			"a list of structures", "TagSprocket",
			`{"Tags":[{"Key":"k","Value":"v"}]}`,
			[]string{
				"    .tags(",
				"        aws_sdk_widgets::types::SprocketTag::builder()",
				`            .key("k")`,
				`            .value("v")`,
				"            .build()",
				"    )",
			},
		},
		{
			// A structure inside a structure is another builder chain, and
			// the nested build() obeys rustBuilderIsFallible on its own shape:
			// RetentionPolicy.Days is required without @default, so it is
			// fallible where the WidgetSettings around it is not.
			"a structure inside a structure", "UpdateWidget",
			`{"Settings":{"Retention":{"Days":7,"Enabled":true}}}`,
			[]string{
				"    .settings(",
				"        aws_sdk_widgets::types::WidgetSettings::builder()",
				"            .retention(",
				"                aws_sdk_widgets::types::RetentionPolicy::builder()",
				"                    .days(7)",
				"                    .enabled(true)",
				"                    .build()",
				`                    .map_err(|err| scenario::build_error("Settings.Retention", err))?`,
				"            )",
				"            .build()",
				"    )",
			},
		},
		{
			// A list member of a structure builder is the same repeated
			// setter it is at the top level — smithy-rs appends one element
			// per call at every depth.
			"a list of strings inside a structure", "UpdateWidget",
			`{"Settings":{"Cogs":["c-00000001","c-00000002"]}}`,
			[]string{
				"        aws_sdk_widgets::types::WidgetSettings::builder()",
				`            .cogs("c-00000001")`,
				`            .cogs("c-00000002")`,
				"            .build()",
			},
		},
		{
			"a list of structures inside a structure", "UpdateWidget",
			`{"Settings":{"Tags":[{"Key":"k","Value":"v"}]}}`,
			[]string{
				"        aws_sdk_widgets::types::WidgetSettings::builder()",
				"            .tags(",
				"                aws_sdk_widgets::types::SprocketTag::builder()",
				`                    .key("k")`,
				`                    .value("v")`,
				"                    .build()",
				"            )",
				"            .build()",
			},
		},
		{
			"a map inside a structure", "UpdateWidget",
			`{"Settings":{"Labels":{"compat":"scenario","team":"platform"}}}`,
			[]string{
				`            .labels("compat", "scenario")`,
				`            .labels("team", "platform")`,
			},
		},
		{
			// The Binder is asked for the leaf's own path, however deep the
			// composite around it is.
			"an expression nested two composites deep", "UpdateWidget",
			`{"Settings":{"Tags":[{"Key":{"$ref":"t"}}]}}`,
			[]string{`                    .key(b.string("Settings.Tags[0].Key")?)`},
		},
		{
			// A map whose values are lists is one setter per entry, and the
			// setter takes the whole Vec (CreateExtension.Actions), so the
			// list is a vec! of builder chains rather than repeated calls.
			"a map of lists of structures inside a structure", "UpdateWidget",
			`{"Settings":{"Hooks":{"a":[{"Key":"k1"},{"Key":"k2","Value":"v2"}],"b":[]}}}`,
			[]string{
				"            .hooks(",
				`                "a",`,
				"                vec![",
				"                    aws_sdk_widgets::types::SprocketTag::builder()",
				`                        .key("k1")`,
				"                        .build(),",
				`                        .value("v2")`,
				`            .hooks("b", vec![])`,
			},
		},
		{
			"an expression inside a list inside a map", "UpdateWidget",
			`{"Settings":{"Hooks":{"a":[{"Key":{"$ref":"t"}}]}}}`,
			[]string{`                        .key(b.string("Settings.Hooks.a[0].Key")?)`},
		},
		{
			"an expression into a string", "GetWidget",
			`{"WidgetId":{"$ref":"widget.id"}}`,
			[]string{`    .widget_id(b.string("WidgetId")?)`},
		},
		{
			// The Binder answers with a String, so the enum conversion stays.
			"an expression into an enum", "CreateWidget",
			`{"Color":{"$name":"c"}}`,
			[]string{`    .color(aws_sdk_widgets::types::Color::from(b.string("Color")?.as_str()))`},
		},
		{
			// The member's path inside the params document is what the Binder is
			// asked for, and what a binding failure reports.
			"an expression inside a composite", "TagWidget",
			`{"Tags":{"compat":{"$ref":"t"}}}`,
			[]string{`    .tags("compat", b.string("Tags.compat")?)`},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var params map[string]any
			if err := decodeStrict([]byte(tc.params), &params); err != nil {
				t.Fatal(err)
			}
			lines, _, err := rustCallLines(gen.model, crate, tc.op, params)
			if err != nil {
				t.Fatalf("rustCallLines(%s): %v", tc.op, err)
			}
			source := strings.Join(lines, "\n")
			for _, want := range tc.want {
				if !strings.Contains(source, want) {
					t.Errorf("%s does not spell %q:\n%s", tc.op, want, source)
				}
			}
			// Every call ends in the send, which is what -explain puts the
			// assignment in front of.
			if lines[len(lines)-1] != "request.send().await" {
				t.Errorf("the last line is %q, not the call", lines[len(lines)-1])
			}
		})
	}
}

// TestRustSetterCalls_buildsAFallibleBuilderOnlyWhereTheModelRequiresAMember
// pins the one thing about smithy-rs this emitter derives rather than reads:
// a builder for a structure with a required member returns a Result and one
// without returns the structure. Getting it the wrong way round is a compile
// error in the suite, so it is asserted here against both shapes.
func TestRustSetterCalls_buildsAFallibleBuilderOnlyWhereTheModelRequiresAMember(t *testing.T) {
	required := map[string]awsmodel.SnapshotMember{
		"Id": {Target: "smithy.api#String", Traits: map[string]json.RawMessage{"smithy.api#required": json.RawMessage("{}")}},
	}
	// Required *and* defaulted, which is Elastic Load Balancing's
	// Listener.LoadBalancerPort and five other members in the pinned
	// snapshot: the builder fills such a member in with unwrap_or_default,
	// so build() has no Result and a `?` after it does not compile.
	defaulted := map[string]awsmodel.SnapshotMember{
		"Id": {Target: "smithy.api#String", Traits: map[string]json.RawMessage{
			"smithy.api#required": json.RawMessage("{}"),
			"smithy.api#default":  json.RawMessage(`""`),
		}},
	}
	model := &serviceModel{Snapshot: awsmodel.Snapshot{
		Service: "widgets",
		Shapes: map[string]awsmodel.SnapshotShape{
			"EntryList":     {Type: "list", Member: "Entry"},
			"Entry":         {Type: "structure", Members: required},
			"LooseList":     {Type: "list", Member: "Loose"},
			"DefaultedList": {Type: "list", Member: "Defaulted"},
			"Defaulted":     {Type: "structure", Members: defaulted},
			"Loose":         {Type: "structure", Members: map[string]awsmodel.SnapshotMember{"Id": {Target: "smithy.api#String"}}},
			"smithy.api#St": {Type: "string"},
		},
	}}
	value := []any{map[string]any{"Id": "1"}}

	fallible, err := rustSetterCalls(model, "aws_sdk_widgets", "entries", "EntryList", value, "Entries", rustCallIndent, &rustBindings{})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(strings.Join(fallible, "\n"), `.map_err(|err| scenario::build_error("Entries[0]", err))?`) {
		t.Errorf("a builder for a structure with a required member is not fallible:\n%s", strings.Join(fallible, "\n"))
	}

	infallible, err := rustSetterCalls(model, "aws_sdk_widgets", "loose", "LooseList", value, "Loose", rustCallIndent, &rustBindings{})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(strings.Join(infallible, "\n"), "map_err") {
		t.Errorf("a builder for a structure with no required member was written as fallible:\n%s", strings.Join(infallible, "\n"))
	}

	defaulted_, err := rustSetterCalls(model, "aws_sdk_widgets", "defaulted", "DefaultedList", value, "Defaulted", rustCallIndent, &rustBindings{})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(strings.Join(defaulted_, "\n"), "map_err") {
		t.Errorf("a builder whose only required member carries @default was written as fallible:\n%s", strings.Join(defaulted_, "\n"))
	}
}

// TestRustValue_coversTheIRsValueGrammar keeps the naming table total: every
// form the IR admits has a Rust expression, and nothing else does. A subtree
// with no expression in it is one serde_json literal — shorter than the same
// tree broken open, and exactly the JSON the scenario file writes.
func TestRustValue_coversTheIRsValueGrammar(t *testing.T) {
	for _, tc := range []struct {
		name string
		in   string
		want string
	}{
		{"a string", `"hello"`, `scenario::lit(::serde_json::json!("hello"))`},
		{"a number", `30`, `scenario::lit(::serde_json::json!(30))`},
		{"a boolean", `false`, `scenario::lit(::serde_json::json!(false))`},
		{"null", `null`, `scenario::lit(::serde_json::json!(null))`},
		{"a literal list", `["a","b"]`, `scenario::lit(::serde_json::json!(["a", "b"]))`},
		{"a literal object", `{"K":"v"}`, `scenario::lit(::serde_json::json!({"K": "v"}))`},
		{"$name", `{"$name":"q"}`, `scenario::name("q")`},
		{"$ref", `{"$ref":"queue.url"}`, `scenario::context("queue.url")`},
		{"$lit", `{"$lit":{"$weird":1}}`, `scenario::lit(::serde_json::json!({"$weird": 1}))`},
		{
			"$concat", `{"$concat":["a",{"$ref":"q.u"}]}`,
			`scenario::concat(vec![scenario::lit(::serde_json::json!("a")), scenario::context("q.u")])`,
		},
		{
			"$index", `{"$index":[{"$ref":"q.urls"},1]}`,
			`scenario::index(scenario::context("q.urls"), 1)`,
		},
		{
			"an object holding one expression is broken open", `{"K":{"$ref":"r"},"L":"v"}`,
			`scenario::map(vec![("K", scenario::context("r")), ("L", scenario::lit(::serde_json::json!("v")))])`,
		},
		{
			"and so is a list", `["a",{"$name":"n"}]`,
			`scenario::list(vec![scenario::lit(::serde_json::json!("a")), scenario::name("n")])`,
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var v any
			if err := decodeStrict([]byte(tc.in), &v); err != nil {
				t.Fatal(err)
			}
			got, err := rustValue(v, "")
			if err != nil {
				t.Fatalf("rustValue(%s): %v", tc.in, err)
			}
			// Compared with the wrapping folded away: which constructor spells
			// which form is this table's subject, and where the line breaks fall
			// is TestRustValue_wrapsAWideComposite's.
			if flattenRust(got) != tc.want {
				t.Errorf("rustValue(%s) = %s, want %s", tc.in, got, tc.want)
			}
		})
	}

	// A value outside the grammar has no expression, and says so rather than
	// rendering something that would not compile.
	if _, err := rustValue(struct{}{}, ""); err == nil {
		t.Error("a value outside the IR's grammar was rendered")
	}
}

// flattenRust folds a wrapped composite back onto one line: the trailing
// comma a wrapped entry carries goes, and the separator a joined line lost
// comes back.
func flattenRust(source string) string {
	var parts []string
	for _, line := range strings.Split(source, "\n") {
		parts = append(parts, strings.TrimSpace(line))
	}
	joined := strings.Join(parts, "")
	joined = strings.ReplaceAll(joined, ",)", ")")
	joined = strings.ReplaceAll(joined, ",]", "]")
	return regexp.MustCompile(`,(\S)`).ReplaceAllString(joined, ", $1")
}

// TestRustValue_wrapsAWideComposite keeps a generated file reviewable: nothing
// reformats the emitter's output afterwards, so a composite past the width
// budget is broken open here or not at all.
func TestRustValue_wrapsAWideComposite(t *testing.T) {
	var v any
	if err := decodeStrict([]byte(`{"AVeryLongMemberNameIndeed":{"$ref":"a.value.long.enough.to.pass.the.budget"},"Another":"one"}`), &v); err != nil {
		t.Fatal(err)
	}
	got, err := rustValue(v, "\t")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(got, "\n") {
		t.Errorf("a composite past the width budget stayed on one line:\n%s", got)
	}
}

// TestRustString_escapesForRustRatherThanForJSON pins the one place the two
