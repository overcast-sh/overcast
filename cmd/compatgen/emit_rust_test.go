// TestRustItemNamesAreUnique refuses two names that fold to one Rust item
// before the suite fails to build with no indication of which pair caused it.
func TestRustItemNamesAreUnique(t *testing.T) {
	// snake_case puts the group's hyphens and the test name's word boundaries
	// in the same place: svc-gen-a-b/Cd and svc-gen-a/BCd both fold to
	// test_svc_gen_a_b_cd.
	groups := []group{
		{Name: "svc-gen-a-b", Tests: []test{{Name: "Cd"}}},
		{Name: "svc-gen-a", Tests: []test{{Name: "BCd"}}},
	}
	err := rustItemNamesAreUnique("svc", groups)
	if err == nil {
		t.Fatal("two colliding item names were accepted")
	}
	for _, want := range []string{"svc-gen-a-b/Cd", "svc-gen-a/BCd", "test_svc_gen_a_b_cd"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("the collision message lacks %q: %v", want, err)
		}
	}
}

// TestEmitRustIndex_listsEveryEmittedServiceAndCompilesWhenEmpty pins both
// halves of the index: it lists what was emitted, and it still compiles when
// nothing was.
func TestEmitRustIndex_listsEveryEmittedServiceAndCompilesWhenEmpty(t *testing.T) {
	full, err := emitRustIndex([]string{"sqs", "organizations"})
	if err != nil {
		t.Fatal(err)
	}
	source := string(full)
	for _, want := range []string{
		`#[path = "scenarios_organizations_gen.rs"]`,
		"ScenariosOrganizations::new(clients)",
		"ScenariosSqs::new(clients)",
	} {
		if !strings.Contains(source, want) {
			t.Errorf("index does not carry %q:\n%s", want, source)
		}
	}
	if strings.Index(source, "ScenariosOrganizations") > strings.Index(source, "ScenariosSqs") {
		t.Error("the index is not sorted; regeneration would depend on recipe read order")
	}

	empty, err := emitRustIndex(nil)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(empty), "Vec::new()") {
		t.Errorf("the empty index does not compile to an empty list:\n%s", empty)
	}
	if !strings.Contains(string(empty), "_clients: &Arc<AwsClients>") {
		t.Error("the empty index names a used parameter, which would warn")
	}
}

// TestExplainRustRendersTheEmittedCall is the definition-of-done item that there
// is one naming table: `-explain -lang rust` must print the statements the
// emitter writes, not a second description of them.
func TestExplainRustRendersTheEmittedCall(t *testing.T) {
	_, gen := generateFixture(t)
	g, tc, ok := gen.scenario.findTest("widgets-gen-widget", "CreateWidget")
	if !ok {
		t.Fatal("fixture has no CreateWidget")
	}
	explained := renderRust(renderEnv{model: staticModel(gen.model)}, gen.scenario, g, tc)

	emission, err := emitRust(gen)
	if err != nil {
		t.Fatalf("emitRust: %v", err)
	}
	emitted := string(emission.Contents)

	lines, _, err := rustCallLines(gen.model, rustNameCrate(gen.scenario.Client.SDKID), tc.Call.Op, tc.Call.Params)
	if err != nil {
		t.Fatal(err)
	}
	if len(lines) < 4 {
		t.Fatalf("CreateWidget renders %d line(s); the fixture no longer exercises member binding", len(lines))
	}
	for _, line := range lines {
		if !strings.Contains(explained, line) {
			t.Errorf("-explain -lang rust does not render %q:\n%s", line, explained)
		}
		if !strings.Contains(emitted, line) {
			t.Errorf("the emitted source does not contain %q", line)
		}
	}

	// And a checkout that cannot read the snapshot says so rather than printing
	// a spelling that would be a guess.
	broken := renderRust(renderEnv{model: func(string) (*serviceModel, error) { return nil, os.ErrNotExist }}, gen.scenario, g, tc)
	if !strings.Contains(broken, "the shape snapshot could not be read") {
		t.Errorf("-explain does not say why it cannot spell the call:\n%s", broken)
	}
}
