using System.Reflection;
using System.Text;
using Amazon.Runtime;
using Amazon.Runtime.Documents;

namespace OvercastCompat.Scenario;

/// <summary>
/// The AWSSDK for .NET's own member types, as the text table
/// <c>cmd/compatgen</c> spells emitted C# from.
/// </summary>
/// <remarks>
/// The .NET emitter used to derive every member's C# type from the pinned
/// Smithy model, and for most members the two agree. Where they do not, the
/// emitted source does not compile: AWSSDK.CloudWatchLogs types
/// <c>InputLogEvent.Timestamp</c> as <c>DateTime?</c> where the model says
/// <c>long</c>. So the emitter reads the SDK — the .NET counterpart of the
/// go-sdk emitter's load of the vendored Go SDK (#1831). It cannot load .NET
/// assemblies itself: <c>go run -tags dev ./cmd/compatgen -check</c> runs where
/// there is no .NET SDK and no NuGet cache, and must stay offline and
/// byte-reproducible. So the facts it needs are reflected here, once per pin,
/// and committed under <c>sdk-types/</c>, one file per package.
/// <para>Two things keep the committed table honest.
/// <c>SdkTypeTableTests</c> renders the table from the assemblies the suite
/// actually compiles against and fails when a committed file differs, in the
/// image build and in CI's compat-suite-unit-tests job alike. And
/// <c>cmd/compatgen</c> refuses a table whose package versions differ from the
/// pins in <c>OvercastCompat.csproj</c>, offline, so a pin bump that forgot the
/// table fails <c>-check</c> rather than emitting against stale types.</para>
/// <para>Refresh it with the suite's own image build — the command is in
/// compat/suites/dotnet-sdk/README.md § The SDK type table.</para>
/// </remarks>
internal static class SdkTypeTable
{
    /// <summary>The directory the table is committed in, relative to the suite.</summary>
    public const string DirectoryName = "sdk-types";

    /// <summary>
    /// Renders one table file per AWSSDK service assembly found in
    /// <paramref name="directory"/> — every <c>AWSSDK.*.dll</c> except Core,
    /// which declares no service. Keyed by file name.
    /// </summary>
    public static SortedDictionary<string, string> Render(string directory)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var path in Directory.GetFiles(directory, "AWSSDK.*.dll"))
        {
            var package = Path.GetFileNameWithoutExtension(path);
            if (package == "AWSSDK.Core")
            {
                continue;
            }
            files[package + ".txt"] = RenderAssembly(package, Assembly.LoadFrom(path));
        }
        return files;
    }

    /// <summary>
    /// Renders one assembly: a header naming the package and its version, then
    /// every model class and its public properties, sorted.
    /// </summary>
    /// <remarks>
    /// The version is the assembly's file version, which AWSSDK stamps with the
    /// NuGet package version (4.0.102.3) where the assembly version stays at
    /// the major's 4.0.0.0 for strong-name binding; that is the number the
    /// csproj pins and cmd/compatgen compares. A zero fourth part is dropped,
    /// as NuGet drops it when it normalises a version: package 4.0.0 is file
    /// version 4.0.0.0.
    /// </remarks>
    public static string RenderAssembly(string package, Assembly assembly)
    {
        var fileVersion = assembly.GetCustomAttribute<AssemblyFileVersionAttribute>()?.Version
            ?? throw new InvalidOperationException($"{package} carries no AssemblyFileVersion");
        var parsed = Version.Parse(fileVersion);
        var version = parsed.Revision is 0 or -1
            ? $"{parsed.Major}.{parsed.Minor}.{Math.Max(parsed.Build, 0)}"
            : parsed.ToString();

        var classes = assembly.GetExportedTypes()
            .Where(IsModelClass)
            .OrderBy(type => type.FullName, StringComparer.Ordinal)
            .ToList();
        var modelNamespace = classes.Select(type => type.Namespace).Distinct().SingleOrDefault()
            ?? throw new InvalidOperationException($"{package} declares model classes in more than one namespace, or in none");

        var text = new StringBuilder();
        text.Append("# Code generated by the dotnet-sdk suite's sdk-types build target; DO NOT EDIT.\n");
        text.Append("# Refresh: compat/suites/dotnet-sdk/README.md § The SDK type table.\n");
        text.Append($"package {package} {version}\n");
        text.Append($"namespace {modelNamespace}\n");
        foreach (var type in classes)
        {
            text.Append($"class {type.Name}\n");
            var properties = type.GetProperties(BindingFlags.Public | BindingFlags.Instance)
                .Where(property => property.GetIndexParameters().Length == 0
                    && property.DeclaringType != typeof(AmazonWebServiceRequest)
                    && property.DeclaringType != typeof(AmazonWebServiceResponse))
                .OrderBy(property => property.Name, StringComparer.Ordinal);
            foreach (var property in properties)
            {
                text.Append($"  {property.Name} {Spell(property.PropertyType, modelNamespace)}\n");
            }
        }
        return text.ToString();
    }

    /// <summary>
    /// A class in the service's model namespace that a request or response can
    /// hold: the requests and responses themselves and every structure, but no
    /// exception — an error is matched by name, never built or walked by path.
    /// </summary>
    private static bool IsModelClass(Type type) =>
        type.IsClass
        && !type.IsAbstract
        && type.Namespace is { } ns
        && ns.StartsWith("Amazon.", StringComparison.Ordinal)
        && ns.EndsWith(".Model", StringComparison.Ordinal)
        && !typeof(Exception).IsAssignableFrom(type);

    /// <summary>
    /// Spells a property type in the table's closed grammar.
    /// </summary>
    /// <remarks>
    /// <code>
    /// string bool byte sbyte short ushort int uint long ulong float double decimal
    /// DateTime MemoryStream Stream Document      — each with a trailing ? when Nullable
    /// enum:&lt;Name&gt;                                 — a ConstantClass, AWSSDK's enum
    /// class:&lt;Name&gt;                                — a class in this model namespace
    /// List&lt;T&gt;  Dictionary&lt;K,V&gt;                    — the SDK's two collections
    /// type:&lt;FullName&gt;                             — anything else, verbatim
    /// </code>
    /// Everything cmd/compatgen does not recognise it refuses, so the last
    /// form is there to be read by a person, never to be spelled.
    /// </remarks>
    internal static string Spell(Type type, string modelNamespace)
    {
        if (Nullable.GetUnderlyingType(type) is { } underlying)
        {
            return Spell(underlying, modelNamespace) + "?";
        }
        if (type.IsGenericType)
        {
            var definition = type.GetGenericTypeDefinition();
            var args = type.GetGenericArguments().Select(arg => Spell(arg, modelNamespace));
            if (definition == typeof(List<>))
            {
                return $"List<{string.Join(",", args)}>";
            }
            if (definition == typeof(Dictionary<,>))
            {
                return $"Dictionary<{string.Join(",", args)}>";
            }
            // Spelled by name and arguments rather than FullName, which for a
            // constructed generic carries assembly-qualified arguments and so
            // the runtime's own version.
            var name = definition.FullName![..definition.FullName!.IndexOf('`')];
            return $"type:{name}<{string.Join(",", args)}>";
        }
        if (Primitive.TryGetValue(type, out var keyword))
        {
            return keyword;
        }
        if (typeof(ConstantClass).IsAssignableFrom(type))
        {
            return $"enum:{type.Name}";
        }
        if (type.Namespace == modelNamespace && type.IsClass)
        {
            return $"class:{type.Name}";
        }
        return $"type:{type.FullName}";
    }

    private static readonly Dictionary<Type, string> Primitive = new()
    {
        [typeof(string)] = "string",
        [typeof(bool)] = "bool",
        [typeof(byte)] = "byte",
        [typeof(sbyte)] = "sbyte",
        [typeof(short)] = "short",
        [typeof(ushort)] = "ushort",
        [typeof(int)] = "int",
        [typeof(uint)] = "uint",
        [typeof(long)] = "long",
        [typeof(ulong)] = "ulong",
        [typeof(float)] = "float",
        [typeof(double)] = "double",
        [typeof(decimal)] = "decimal",
        [typeof(DateTime)] = "DateTime",
        [typeof(MemoryStream)] = "MemoryStream",
        [typeof(Stream)] = "Stream",
        [typeof(Document)] = "Document",
    };
}
